"""Generate dart/ipixel_fx/lib/src/fonts_data.dart from the X11 misc-fixed bitmap fonts.

The misc-fixed fonts are public domain. Usage:  python3 -I tools/gen_pixel_fonts.py
"""
import gzip, io, sys
from PIL import PcfFontFile, Image

FONTS = [("tiny", "4x6"), ("small", "5x7"), ("medium", "6x10"), ("large", "6x13")]
out = ["// GENERATED by tools/gen_pixel_fonts.py from X11 misc-fixed (public domain). Do not edit.",
       "part of 'fonts.dart';", ""]
for name, f in FONTS:
    with gzip.open(f"/usr/share/fonts/X11/misc/{f}.pcf.gz") as fp:
        pcf = PcfFontFile.PcfFontFile(io.BytesIO(fp.read()))
    w, h = map(int, f.split("x"))
    rows = []
    for code in range(32, 127):
        g = pcf.glyph[code]
        img = Image.new("1", (w, h), 0)
        if g is not None:
            img.paste(g[3].convert("1"), (0, 0))  # misc-fixed glyphs are full w x h cells
        rows.append(img)
    out.append(f"const _{name}W = {w}, _{name}H = {h};")
    out.append(f"const _{name}Data = <int>[")
    for img in rows:
        vals = []
        for y in range(h):
            bits = 0
            for x in range(w):
                if img.getpixel((x, y)):
                    bits |= 1 << (w - 1 - x)
            vals.append(bits)
        out.append("  " + ", ".join(str(v) for v in vals) + ",")
    out.append("];")
    out.append("")
open(sys.argv[1] if len(sys.argv) > 1 else "dart/ipixel_fx/lib/src/fonts_data.dart", "w").write("\n".join(out))
