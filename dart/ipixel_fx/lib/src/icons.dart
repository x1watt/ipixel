import 'canvas.dart';

/// 8x8 one-colour icons as row bitmasks (bit 7 = leftmost). Drawn by [Icons8.draw].
class Icons8 {
  static const heart = [0x66, 0xFF, 0xFF, 0xFF, 0x7E, 0x3C, 0x18, 0x00];
  static const star = [0x18, 0x18, 0xFF, 0x7E, 0x3C, 0x66, 0x42, 0x00];
  static const smile = [0x3C, 0x42, 0xA5, 0x81, 0xA5, 0x99, 0x42, 0x3C];
  static const bell = [0x18, 0x3C, 0x3C, 0x3C, 0x7E, 0x7E, 0x18, 0x00];
  static const mail = [0x00, 0xFF, 0xC3, 0xA5, 0x99, 0x81, 0xFF, 0x00];
  static const sun = [0x18, 0x5A, 0x3C, 0xFF, 0xFF, 0x3C, 0x5A, 0x18];
  static const cloud = [0x00, 0x1C, 0x3E, 0x7F, 0xFF, 0xFF, 0x7E, 0x00];
  static const rain = [0x1C, 0x3E, 0x7F, 0xFF, 0x7E, 0x24, 0x48, 0x90];
  static const note = [0x0C, 0x0A, 0x09, 0x09, 0x09, 0x79, 0xF9, 0x70];
  static const arrowR = [0x08, 0x0C, 0xFE, 0xFF, 0xFF, 0xFE, 0x0C, 0x08];
  static const arrowL = [0x10, 0x30, 0x7F, 0xFF, 0xFF, 0x7F, 0x30, 0x10];
  static const check = [0x00, 0x01, 0x03, 0x86, 0xCC, 0x78, 0x30, 0x00];
  static const cross = [0xC3, 0x66, 0x3C, 0x18, 0x18, 0x3C, 0x66, 0xC3];
  static const bolt = [0x0C, 0x18, 0x30, 0x7E, 0x0C, 0x18, 0x30, 0x20];
  static const skull = [0x3C, 0x7E, 0xDB, 0xFF, 0xFF, 0x5A, 0x3C, 0x24];
  static const ghost = [0x3C, 0x7E, 0x5A, 0xFF, 0xFF, 0xFF, 0xFF, 0xA5];
  static const coffee = [0x00, 0x7C, 0x7E, 0x7E, 0x7C, 0x7C, 0x3C, 0x7E];
  static const home = [0x18, 0x3C, 0x7E, 0xFF, 0x7E, 0x66, 0x66, 0x66];
  static const battery = [0x7E, 0x42, 0x5B, 0x5B, 0x5B, 0x42, 0x7E, 0x00];
  static const mic = [0x18, 0x3C, 0x3C, 0x3C, 0x18, 0x7E, 0x18, 0x3C];

  static const all = <String, List<int>>{
    'heart': heart, 'star': star, 'smile': smile, 'bell': bell, 'mail': mail, 'sun': sun, 'cloud': cloud,
    'rain': rain, 'note': note, 'arrowR': arrowR, 'arrowL': arrowL, 'check': check, 'cross': cross,
    'bolt': bolt, 'skull': skull, 'ghost': ghost, 'coffee': coffee, 'home': home, 'battery': battery, 'mic': mic,
  };

  static void draw(PanelCanvas c, List<int> icon, int x, int y, int color, {int scale = 1}) {
    for (var row = 0; row < 8; row++) {
      for (var col = 0; col < 8; col++) {
        if ((icon[row] >> (7 - col)) & 1 == 1) {
          scale == 1 ? c.set(x + col, y + row, color) : c.fillRect(x + col * scale, y + row * scale, scale, scale, color);
        }
      }
    }
  }
}
